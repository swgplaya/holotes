def translate(
    key: str,
    language: object = DEFAULT_LANGUAGE,
    **values: Any,
) -> str:
    """Возвращает перевод по ключу с русским fallback."""

    normalized_language = normalize_language(
        language
    )

    localized_translations = TRANSLATIONS.get(
        normalized_language,
        {},
    )

    template = localized_translations.get(key)

    if template is None:
        template = TRANSLATIONS[
            DEFAULT_LANGUAGE
        ].get(
            key,
            key,
        )

    if not values:
        return template

    try:
        return template.format(**values)
    except KeyError as exc:
        missing_value = str(exc.args[0])

        raise ValueError(
            "Для перевода "
            f"'{key}' не передано значение "
            f"'{missing_value}'."
        ) from exc


def find_translation_issues() -> tuple[str, ...]:
    """Проверяет полноту словарей локализации."""

    all_keys: set[str] = set()

    for language_translations in TRANSLATIONS.values():
        all_keys.update(language_translations)

    issues: list[str] = []

    for language in SUPPORTED_LANGUAGES:
        language_keys = set(
            TRANSLATIONS.get(language, {})
        )

        missing_keys = sorted(
            all_keys - language_keys
        )

        if missing_keys:
            issues.append(
                f"{language}: отсутствуют ключи: "
                + ", ".join(missing_keys)
            )

    return tuple(issues)
